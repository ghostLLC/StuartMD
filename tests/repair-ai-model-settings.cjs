"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { JSDOM } = require("jsdom");
const root = path.resolve(__dirname, "..");
const html = fs.readFileSync(path.join(root, "web/index.html"), "utf8");
const dom = new JSDOM(html, { runScripts: "outside-only", url: "https://stuart.local/" });
const { window } = dom;
assert.equal(window.document.querySelector("#ai-mm-provider"), null, "日常模型选择应直接显示已保存模型");
assert.equal(window.document.querySelector("#ai-mm-model"), null, "日常切换无需手工输入型号");
console.log("日常模型入口检查通过");
async function verifySavedConfiguration() {
  const directory = process.argv[2];
  assert.ok(directory, "完整检查需要真实配置副本的独立目录");
  const before = JSON.parse(fs.readFileSync(path.join(directory, "picker-snapshot-before.json"), "utf8"));
  const after = JSON.parse(fs.readFileSync(path.join(directory, "picker-snapshot-after.json"), "utf8"));
  assert.notEqual(before.settingsRevision, after.settingsRevision);
  window.structuredClone = structuredClone;
  window.eval(fs.readFileSync(path.join(root, "web/js/ui/model-picker.js"), "utf8"));
  window.eval(fs.readFileSync(path.join(root, "web/js/ui/ai-settings.js"), "utf8"));
  const anchor = window.document.querySelector("#btn-ai-model"), secondAnchor = window.document.createElement("button"); window.document.body.append(secondAnchor);
  const selected = [];
  const first = window.StuartModelPicker.create({ anchor, onSelect: id => selected.push(id), onManage: () => {} });
  const second = window.StuartModelPicker.create({ anchor: secondAnchor, onSelect: id => selected.push(id), onManage: () => {} });
  first.open(before);
  const panel = window.document.getElementById(anchor.getAttribute("aria-controls")), search = panel.querySelector("input");
  assert.equal(panel.querySelectorAll("[role=option]").length, before.ai.models.length);
  assert.ok(new Set(before.ai.models.map(model => model.provider_id)).size > 1);
  search.value = "DeepSeek"; search.dispatchEvent(new window.Event("input", { bubbles: true }));
  assert.ok(panel.querySelectorAll("[role=option]").length >= 2);
  search.dispatchEvent(new window.KeyboardEvent("keydown", { key: "ArrowDown", bubbles: true }));
  const focused = window.document.activeElement.dataset.modelId; assert.ok(focused);
  first.refresh(after);
  assert.equal(search.value, "DeepSeek"); assert.equal(window.document.activeElement.dataset.modelId, focused);
  window.document.activeElement.click(); await Promise.resolve();
  assert.equal(selected[0], focused); assert.equal(panel.hidden, true); assert.equal(window.document.activeElement, anchor);
  first.open(after); second.open(after); assert.equal(panel.hidden, true);
  const secondPanel = window.document.getElementById(secondAnchor.getAttribute("aria-controls"));
  secondPanel.querySelector("input").dispatchEvent(new window.KeyboardEvent("keydown", { key: "Escape", bubbles: true }));
  assert.equal(secondPanel.hidden, true); assert.equal(window.document.activeElement, secondAnchor);
  const settings = window.StuartAISettings.mount(window.document.querySelector("#set-ai-section"), before);
  assert.equal(window.document.querySelectorAll("#ai-saved-models > [data-model-id]").length, before.ai.models.length);
  await settings.openAdd();
  assert.equal(window.document.querySelectorAll(".ai-catalog-option input[type=checkbox]").length, 2);
  assert.equal(window.document.querySelector(".ai-editor input[type=password]").value, "");
  settings.dispose();
  const model = before.ai.models.find(item => item.provider_id === before.ai.providers.find(provider => provider.type === "deepseek").id);
  await settings.openModel(model.id);
  const name = window.document.querySelector(".ai-editor input[type=text]"); name.value = "阅读时使用的显示名称"; name.dispatchEvent(new window.Event("input", { bubbles: true }));
  const revision = settings.editing.revision; settings.refresh(after);
  assert.equal(name.value, "阅读时使用的显示名称"); assert.equal(settings.editing.revision, revision); assert.equal(settings.editing.dirty, true);
  assert.ok(window.document.querySelector(".ai-editor [data-error]").textContent.includes("当前输入"));
  const preferencesInput = window.document.querySelector(".ai-preferences textarea"); preferencesInput.value = "保留正在填写的回答风格"; preferencesInput.dispatchEvent(new window.Event("input", { bubbles: true }));
  settings.refresh(before); assert.equal(preferencesInput.value, "保留正在填写的回答风格");
  settings.dispose(); first.dispose(); second.dispose(); dom.window.close();
  console.log("真实保存配置的跨厂商列表、两个选择组件、键盘操作及编辑输入保留检查通过；窗口与视觉检查 SkippedByUser");
}
verifySavedConfiguration().catch(error => { console.error(error); process.exitCode = 1; });
