"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { ConversationStore } = require("../web/js/core/conversation-store.js");
const evidence = JSON.parse(fs.readFileSync(path.join(__dirname, "../docs/validation/3.5.12/conversation-draft.json"), "utf8"));
const store = new ConversationStore(), quick = [], companion = [];
store.subscribe(value => quick.push(value)); store.subscribe(value => companion.push(value));
store.activate(evidence.before.draft.target); store.hydrate(evidence.before);
const message = evidence.before.messages[0];
store.setRequest({ requestId: message.requestId, turnId: message.turnId, sessionId: message.sessionId, text: message.content, status: message.completionStatus }, evidence.before.draft.target);
store.acknowledgeDraft(evidence.savedDraft, store.current().draftEdit);
assert.equal(store.snapshot().target.documentKey, evidence.savedDraft.target.documentKey);
assert.equal(store.snapshot().draft.draftVersion, evidence.savedDraft.draftVersion);
store.setRequest(null, evidence.before.draft.target);
assert.equal(store.snapshot().activeRequest, null);
store.hydrate(evidence.after);
assert.equal(store.snapshot().sessionVersion, evidence.after.session.sessionVersion);
assert.equal(store.snapshot().draft.sessionId, evidence.after.session.sessionId);
const actualQuestion = evidence.before.draft.question;
store.updateDraft({ question: actualQuestion });
store.setDraftConflict(evidence.after);
assert.equal(store.snapshot().draft.question, actualQuestion);
assert.equal(store.snapshot().draftConflict.draft.question, evidence.after.draft.question);
assert.equal(store.snapshot().draftDirty, true);
store.hydrate(evidence.after);
assert.equal(store.snapshot().draftConflict, null);
assert.equal(store.snapshot().draftDirty, false);
assert.deepEqual(quick, companion);
assert.equal(store.snapshot().messages[0].messageId, message.messageId);
console.log(JSON.stringify({ status: "Passed", sqliteEvidence: "docs/validation/3.5.12/conversation-draft.json", subscriptions: 2, notifications: quick.length, persistentIdentity: "Passed", requestIdentityAfterSave: "Passed", sessionVersion: "Passed", draftConflictPreservation: "Passed" }, null, 2));
